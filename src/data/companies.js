export function flattenJobs(list) {
  return list.flatMap((company) =>
    company.jobs.map((job) => ({
      ...job,
      companyId: company.id,
      companyName: company.name,
      companySlug: company.slug,
      city: company.city,
      state: company.state,
      sector: company.sector,
    })),
  );
}

export function findCompanyBySlug(list, slug) {
  return list.find((company) => company.slug === slug) ?? null;
}
